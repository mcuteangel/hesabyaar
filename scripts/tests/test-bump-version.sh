#!/usr/bin/env sh
# Tests for scripts/bump-version.sh (app version + optional Rust core bump).
#
# POSIX-compatible: runs with bash, ash/busybox, or dash. Requires python3
# for the Cargo.lock refresh path.
# Usage: ./scripts/tests/test-bump-version.sh
set -eu

# shellcheck disable=SC1007 # CDPATH= applies to this cd only; intentional (same idiom as other scripts/tests)
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
BUMP="$HERE/../bump-version.sh"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP" 2>/dev/null || true' EXIT

pass=0
fail=0
test_id=0

setup_files() {
  test_id=$((test_id + 1))
  D="$TMP/case-$test_id"
  mkdir -p "$D/rust"
  printf '0.18.0' > "$D/VERSION"
  printf '# Changelog\n\nAll notable changes to this project will be documented in this file.\n\nThe format is based on [Keep a Changelog](https://keepachangelog.com/en/1.0.0/),\nand this project adheres to [Semantic Versioning](https://semver.org/spec/v2.0.0.html).\n\n' > "$D/CHANGELOG.md"
  printf '[workspace]\nmembers = ["hesabyar-core"]\n\n[workspace.package]\nversion = "0.7.0"\nedition = "2021"\n' > "$D/rust/Cargo.toml"
  printf '# This file is automatically generated by Cargo.\nversion = 4\n\n[[package]]\nname = "hesabyar-core"\nversion = "0.7.0"\ndependencies = [\n "serde",\n]\n\n[[package]]\nname = "uniffi-gen"\nversion = "0.1.0"\n' > "$D/rust/Cargo.lock"
}

# Runs bump in $D with the given args; stdout goes to $D/stdout.txt.
run_bump() {
  dir=$1
  shift
  (cd "$dir" && VERSION_FILE=VERSION CHANGELOG_FILE=CHANGELOG.md CARGO_MANIFEST=rust/Cargo.toml CARGO_LOCK=rust/Cargo.lock bash "$BUMP" "$@") >"$dir/stdout.txt" 2>"$dir/stderr.txt"
}

assert_contains() {
  file=$1
  needle=$2
  name=$3
  if grep -qF "$needle" "$file"; then
    echo "PASS $name"
    pass=$((pass + 1))
  else
    echo "FAIL $name: '$needle' not found in $file"
    fail=$((fail + 1))
  fi
}

assert_not_contains() {
  file=$1
  needle=$2
  name=$3
  if grep -qF "$needle" "$file"; then
    echo "FAIL $name: '$needle' unexpectedly found in $file"
    fail=$((fail + 1))
  else
    echo "PASS $name"
    pass=$((pass + 1))
  fi
}

assert_status() {
  want=$1
  got=$2
  name=$3
  if [ "$got" = "$want" ]; then
    echo "PASS $name (status=$got)"
    pass=$((pass + 1))
  else
    echo "FAIL $name: expected status $want, got $got"
    fail=$((fail + 1))
  fi
}

# --- Test 1: app-only patch bump leaves core untouched ---
setup_files
set +e
run_bump "$D" patch
status=$?
set -e
assert_status 0 "$status" "app-only patch exits 0"
assert_contains "$D/stdout.txt" "0.18.1" "app-only patch prints new app version"
assert_contains "$D/VERSION" "0.18.1" "app-only patch writes VERSION"
assert_contains "$D/CHANGELOG.md" "## [0.18.1]" "app-only patch prepends changelog entry"
assert_contains "$D/rust/Cargo.toml" 'version = "0.7.0"' "app-only patch leaves core version"
assert_contains "$D/rust/Cargo.lock" 'version = "0.7.0"' "app-only patch leaves lock version"

# --- Test 2: app patch + core minor bumps manifest and lock, others untouched ---
setup_files
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 0 "$status" "app patch + core minor exits 0"
assert_contains "$D/stdout.txt" "0.18.1" "app patch + core minor prints app version only"
assert_contains "$D/VERSION" "0.18.1" "app patch + core minor writes VERSION"
assert_contains "$D/rust/Cargo.toml" 'version = "0.8.0"' "core minor writes manifest"
assert_contains "$D/rust/Cargo.toml" 'edition = "2021"' "core minor keeps manifest edition"
if grep -A1 'name = "hesabyar-core"' "$D/rust/Cargo.lock" | grep -q 'version = "0.8.0"'; then
  echo "PASS core minor refreshes lock entry"
  pass=$((pass + 1))
else
  echo "FAIL core minor refreshes lock entry"
  fail=$((fail + 1))
fi
if grep -A1 'name = "uniffi-gen"' "$D/rust/Cargo.lock" | grep -q 'version = "0.1.0"'; then
  echo "PASS core minor leaves other lock entries"
  pass=$((pass + 1))
else
  echo "FAIL core minor leaves other lock entries"
  fail=$((fail + 1))
fi
assert_contains "$D/stderr.txt" "Core version bumped: 0.7.0 -> 0.8.0" "core minor reports bump on stderr"

# --- Test 3: core "null" skips the core bump ---
setup_files
set +e
run_bump "$D" patch null
status=$?
set -e
assert_status 0 "$status" "core null exits 0"
assert_contains "$D/rust/Cargo.toml" 'version = "0.7.0"' "core null leaves manifest"
assert_contains "$D/rust/Cargo.lock" 'version = "0.7.0"' "core null leaves lock"

# --- Test 4: invalid core bump type fails ---
setup_files
set +e
run_bump "$D" patch banana
status=$?
set -e
assert_status 1 "$status" "invalid core bump type fails"
assert_contains "$D/VERSION" "0.18.0" "invalid core bump type leaves VERSION untouched"
assert_not_contains "$D/CHANGELOG.md" "## [0.18.1]" "invalid core bump type leaves CHANGELOG untouched"

# --- Test 5: app major + core major reset minor and patch ---
setup_files
set +e
run_bump "$D" major major
status=$?
set -e
assert_status 0 "$status" "app major + core major exits 0"
assert_contains "$D/VERSION" "1.0.0" "app major writes 1.0.0"
assert_contains "$D/rust/Cargo.toml" 'version = "1.0.0"' "core major writes 1.0.0"

# --- Test 6: core bump without manifest fails ---
setup_files
rm "$D/rust/Cargo.toml"
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 1 "$status" "core bump without manifest fails"
assert_contains "$D/VERSION" "0.18.0" "core bump without manifest leaves VERSION untouched"

# --- Test 7: lock block tolerates comments and blank lines ---
setup_files
printf '# This file is automatically generated by Cargo.\nversion = 4\n\n[[package]]\nname = "hesabyar-core"\n# the core engine\n\nversion = "0.7.0"\ndependencies = [\n "serde",\n]\n\n[[package]]\nname = "uniffi-gen"\nversion = "0.1.0"\n' > "$D/rust/Cargo.lock"
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 0 "$status" "lock with comments exits 0"
if grep -A3 'name = "hesabyar-core"' "$D/rust/Cargo.lock" | grep -q 'version = "0.8.0"'; then
  echo "PASS lock with comments refreshes entry"
  pass=$((pass + 1))
else
  echo "FAIL lock with comments refreshes entry"
  fail=$((fail + 1))
fi

# --- Test 8: dotted-section version lines are ignored ---
setup_files
printf '[workspace]\nmembers = ["hesabyar-core"]\n\n[workspace.package]\nversion = "0.7.0"\nedition = "2021"\n\n[workspace.dependencies]\nversion = "9.9.9"\n' > "$D/rust/Cargo.toml"
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 0 "$status" "dotted-section manifest exits 0"
assert_contains "$D/rust/Cargo.toml" 'version = "0.8.0"' "dotted-section manifest bumps workspace version"
assert_contains "$D/rust/Cargo.toml" 'version = "9.9.9"' "dotted-section version line untouched"

# --- Test 9: missing workspace version fails without corrupting ---
setup_files
printf '[workspace]\nmembers = ["hesabyar-core"]\n\n[workspace.package]\nedition = "2021"\n\n[workspace.dependencies]\nversion = "9.9.9"\n' > "$D/rust/Cargo.toml"
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 1 "$status" "missing workspace version fails"
assert_contains "$D/VERSION" "0.18.0" "missing workspace version leaves VERSION untouched"
assert_contains "$D/rust/Cargo.toml" 'version = "9.9.9"' "missing workspace version leaves manifest untouched"

# --- Test 10: missing python3 fails before any write ---
setup_files
BIN="$D/bin"
mkdir -p "$BIN"
for t in bash awk cat date grep mv tail tr; do
  for dir in /usr/bin /bin; do
    if [ -x "$dir/$t" ]; then ln -s "$dir/$t" "$BIN/$t"; break; fi
  done
done
set +e
(cd "$D" && VERSION_FILE=VERSION CHANGELOG_FILE=CHANGELOG.md CARGO_MANIFEST=rust/Cargo.toml CARGO_LOCK=rust/Cargo.lock PATH="$BIN" bash "$BUMP" patch minor) 2>"$D/stderr.txt"
status=$?
set -e
assert_status 1 "$status" "missing python3 fails"
assert_contains "$D/stderr.txt" "python3 is required" "missing python3 reports its cause"
assert_contains "$D/VERSION" "0.18.0" "missing python3 leaves VERSION untouched"
assert_contains "$D/rust/Cargo.toml" 'version = "0.7.0"' "missing python3 leaves manifest untouched"
assert_not_contains "$D/CHANGELOG.md" "## [0.18.1]" "missing python3 leaves CHANGELOG untouched"

# --- Test 11: indented lock lines are matched and keep their indent ---
setup_files
printf '# This file is automatically generated by Cargo.\nversion = 4\n\n[[package]]\n  name = "hesabyar-core"\n  version = "0.7.0"\n\n[[package]]\nname = "uniffi-gen"\nversion = "0.1.0"\n' > "$D/rust/Cargo.lock"
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 0 "$status" "indented lock lines exit 0"
assert_contains "$D/rust/Cargo.lock" '  version = "0.8.0"' "indented lock line keeps its indent"

# --- Test 12: stale lock entry fails before any write ---
setup_files
printf '# This file is automatically generated by Cargo.\nversion = 4\n\n[[package]]\nname = "hesabyar-core"\nversion = "0.6.0"\n\n[[package]]\nname = "uniffi-gen"\nversion = "0.1.0"\n' > "$D/rust/Cargo.lock"
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 1 "$status" "stale lock entry fails"
assert_contains "$D/VERSION" "0.18.0" "stale lock entry leaves VERSION untouched"
assert_contains "$D/rust/Cargo.toml" 'version = "0.7.0"' "stale lock entry leaves manifest untouched"
assert_not_contains "$D/CHANGELOG.md" "## [0.18.1]" "stale lock entry leaves CHANGELOG untouched"

# --- Test 13: staged write failure leaves everything untouched ---
# The staged manifest path is a directory, so the staging redirect fails
# (a read-only directory would not stop root, so permissions can't force
# this failure here).
setup_files
mkdir -p "$D/rust/Cargo.toml.tmp"
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 1 "$status" "staged write failure fails"
assert_contains "$D/VERSION" "0.18.0" "staged write failure leaves VERSION untouched"
assert_not_contains "$D/CHANGELOG.md" "## [0.18.1]" "staged write failure leaves CHANGELOG untouched"
assert_contains "$D/rust/Cargo.toml" 'version = "0.7.0"' "staged write failure leaves manifest untouched"

# --- Test 14: single-quoted manifest version bumps ---
setup_files
printf '[workspace]\nmembers = ["hesabyar-core"]\n\n[workspace.package]\nversion = '"'"'0.7.0'"'"'\nedition = "2021"\n' > "$D/rust/Cargo.toml"
set +e
run_bump "$D" patch minor
status=$?
set -e
assert_status 0 "$status" "single-quoted manifest exits 0"
assert_contains "$D/rust/Cargo.toml" 'version = "0.8.0"' "single-quoted manifest bumps version"
assert_contains "$D/rust/Cargo.lock" 'version = "0.8.0"' "single-quoted manifest refreshes lock"

echo ""
echo "$pass passed, $fail failed"
[ "$fail" -eq 0 ]
